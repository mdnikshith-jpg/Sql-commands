-- =========================================================
-- NUMERIC FUNCTIONS (MySQL)
-- =========================================================

SELECT ABS(-100) AS absolute_value;
SELECT CEIL(10.2) AS ceiling_value;
SELECT FLOOR(10.9) AS floor_value;
SELECT ROUND(12.5678, 2) AS rounded_value;
SELECT TRUNCATE(12.5678, 2) AS truncated_value;
SELECT POWER(2, 5) AS power_value;
SELECT SQRT(81) AS square_root;
SELECT MOD(17, 5) AS remainder;
SELECT GREATEST(10, 50, 30) AS greatest_value;
SELECT LEAST(10, 50, 30) AS smallest_value;
